// Generates src/win1252-table.ts: how the C# engine turns each UTF-16 code unit into a Windows-1252
// byte when it writes a text with a standard PDF font (PDFCanvas.UnicodeToWin1252, the .NET 1252
// encoder with its best fit fallback: Ā -> A, α -> a, the rest -> ?).
//
// The table is read back from the C# engine itself: a copy of samples/customers.rep whose first
// label prints every code unit from U+0080 to U+FFFF (but the surrogates, tested apart) is run with
// golden-cs, and the bytes of that label are taken from the uncompressed PDF content stream.
//
//   node packages/reportman-text/test/generate-win1252.mjs     (from typescript/)

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../../..');
const golden = path.join(root, 'typescript/tools/golden-cs/bin/Release/net10.0/golden-cs.exe');
const samples = path.join(root, 'samples');
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'rm-win1252-'));

// The .rep reader decodes #<decimal># as one character
const enc = (s) => {
  let r = '';
  for (let k = 0; k < s.length; k++) r += '#' + s.charCodeAt(k) + '#';
  return r;
};

function probe(codes) {
  let xml = fs.readFileSync(path.join(samples, 'customers.rep'), 'utf8');
  const marker = '<WIDETEXT type="WideString">MARE NOSTRUM FINE FOODS</WIDETEXT>';
  if (!xml.includes(marker)) throw new Error('customers.rep changed: the first label is not there');
  const text = enc('BEGIN|') + codes.map((c) => '#' + c + '#').join('') + enc('|END');
  xml = xml.replace(marker, '<WIDETEXT type="WideString">' + text + '</WIDETEXT>');
  const rep = path.join(work, 'probe.rep');
  fs.writeFileSync(rep, xml);
  const pdfPath = path.join(work, 'probe.pdf');
  execFileSync(golden, ['run', rep, path.join(work, 'probe.json'), '--pdf', pdfPath, '--sqlite',
    path.join(samples, 'samples.db')], { stdio: 'inherit' });
  const pdf = fs.readFileSync(pdfPath);
  const start = pdf.indexOf('(BEGIN|');
  const end = pdf.indexOf('|END) Tj', start);
  if (start < 0 || end < 0) throw new Error('The probe text is not in the PDF');
  const raw = pdf.subarray(start + 7, end);
  const out = [];
  for (let i = 0; i < raw.length; i++) {
    if (raw[i] === 0x5c) i++; // \( \) \\ escapes
    out.push(raw[i]);
  }
  if (out.length !== codes.length) throw new Error(`Expected ${codes.length} bytes, got ${out.length}`);
  return out;
}

const codes = [];
for (let c = 0x80; c <= 0xffff; c++) {
  if (c >= 0xd800 && c <= 0xdfff) continue;
  codes.push(c);
}
const bytes = probe(codes);
// Surrogates: a pair and lone halves, one byte each
const sur = probe([0xd83d, 0xde00, 0xd800, 0x41, 0xdc00, 0x42]);
if (sur.join(',') !== '63,63,63,65,63,66') throw new Error('Surrogates: unexpected ' + sur.join(','));
// The ASCII range is the identity (but LF and CR, which break lines, and TAB, which TextRect
// replaces with a space)
const ascii = [];
for (let c = 0; c < 0x80; c++) if (c !== 9 && c !== 10 && c !== 13) ascii.push(c);
const asciiOut = probe(ascii);
ascii.forEach((c, i) => {
  if (asciiOut[i] !== c) throw new Error('ASCII is not the identity at ' + c);
});

const pairs = [];
for (let i = 0; i < codes.length; i++) if (bytes[i] !== 0x3f) pairs.push(codes[i], bytes[i]);

let ts = '// Generated by test/generate-win1252.mjs from the C# engine. Do not edit.\n';
ts += '//\n// The code units from U+0080 that the .NET Windows-1252 encoder (with its best fit fallback)\n';
ts += '// writes as a byte other than ?, as pairs [code unit, byte]. Below U+0080 the bytes are the\n';
ts += '// code units; every other code unit, the surrogates included, becomes ? (0x3F).\n';
ts += 'export const WIN1252_PAIRS: readonly number[] = [\n';
for (let i = 0; i < pairs.length; i += 16) ts += '  ' + pairs.slice(i, i + 16).map((n) => '0x' + n.toString(16)).join(', ') + ',\n';
ts += '];\n';
fs.writeFileSync(path.join(here, '../src/win1252-table.ts'), ts);
console.log(`${pairs.length / 2} mapped code units written to src/win1252-table.ts`);
fs.rmSync(work, { recursive: true, force: true });
