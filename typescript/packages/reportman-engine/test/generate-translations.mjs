// Generates src/util/reportmanres.en.generated.ts and src/util/reportmanres.es.generated.ts: the
// message tables of the C# engine (Reportman.Drawing/Resources/reportmanres.en and .es), read as
// Translator.LoadFromStream reads them: UTF-16LE, one string per LF, index = string number, and a
// doubled LF is a literal LF inside the current string.
//
//   node packages/reportman-engine/test/generate-translations.mjs     (from typescript/)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../../..');
const resources = path.join(root, 'Reportman.Drawing/Resources');

// Same algorithm as Translator.LoadFromStream (and src/util/translator.ts parseTranslationBytes).
function parse(bytes) {
  const content = [];
  let current = '';
  let foundlf = false;
  const pairs = Math.floor(bytes.length / 2);
  for (let i = 0; i < pairs; i++) {
    const code = (bytes[i * 2 + 1] << 8) + bytes[i * 2];
    if (code === 10) {
      if (foundlf) {
        foundlf = false;
        current += '\n';
      } else foundlf = true;
    } else {
      if (foundlf) {
        content.push(current);
        current = '';
        foundlf = false;
      }
      current += String.fromCharCode(code);
    }
  }
  if (current.length > 0) content.push(current);
  return content;
}

for (const lang of ['en', 'es']) {
  const bytes = fs.readFileSync(path.join(resources, 'reportmanres.' + lang));
  const strings = parse(bytes);
  const outFile = path.resolve(here, `../src/util/reportmanres.${lang}.generated.ts`);
  const header = `// Generated by test/generate-translations.mjs from Reportman.Drawing/Resources/reportmanres.${lang}.
// Do not edit by hand: run \`node packages/reportman-engine/test/generate-translations.mjs\` from typescript/.
/* eslint-disable */

`;
  const lines = strings.map((s) => '  ' + JSON.stringify(s) + ',');
  const body = `export const REPORTMANRES_${lang.toUpperCase()}: readonly string[] = [\n${lines.join('\n')}\n];\n`;
  fs.writeFileSync(outFile, header + body);
  console.log('wrote', outFile, strings.length, 'strings');
}
