// Generates src/util/cultures.generated.ts: the .NET number and date format data of the cultures
// the engine formats with (golden-cs culture-json), plus the era name of each culture, which
// culture-json does not report (read with golden-cs eval and the "gg" date format).
//
//   node packages/reportman-engine/test/generate-cultures.mjs     (from typescript/)

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../../..');
const golden = path.join(root, 'typescript/tools/golden-cs/bin/Release/net10.0/golden-cs.exe');
const outFile = path.resolve(here, '../src/util/cultures.generated.ts');

// The trailing empty name is the invariant culture.
const names = ['en-US', 'es-ES', 'ca-ES', 'pt-BR', 'fr-FR', 'de-DE', 'it-IT', ''];

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), 'rm-cultures-'));
const cultureFile = path.join(tmp, 'cultures.json');
execFileSync(golden, ['culture-json', names.join(','), cultureFile]);
const data = JSON.parse(fs.readFileSync(cultureFile, 'utf8').replace(/^﻿/, ''));

function eraName(name) {
  const cases = path.join(tmp, 'era-cases.json');
  const out = path.join(tmp, 'era-out.json');
  fs.writeFileSync(cases, JSON.stringify([{ expr: 'TODAY', format: 'gg' }]));
  // golden-cs takes the culture name; the invariant culture is ""
  execFileSync(golden, ['eval', cases, out, '--culture', name]);
  const r = JSON.parse(fs.readFileSync(out, 'utf8').replace(/^﻿/, ''));
  if (r[0].error) throw new Error('era of ' + name + ': ' + r[0].message);
  return r[0].formatted;
}

const lower = (o) => {
  const r = {};
  for (const [k, v] of Object.entries(o)) r[k[0].toLowerCase() + k.slice(1)] = v;
  return r;
};

const result = {};
for (const key of Object.keys(data)) {
  const c = data[key];
  const date = lower(c.date);
  date.eraName = eraName(key);
  // ThreeLetterWindowsLanguageName is not in culture-json; the translator only needs to know
  // whether the language is Spanish, which twoLetterISOLanguageName tells.
  result[key] = {
    name: c.name,
    twoLetterISOLanguageName: c.twoLetterISOLanguageName,
    number: lower(c.number),
    date,
  };
}
fs.rmSync(tmp, { recursive: true, force: true });

const header = `// Generated by test/generate-cultures.mjs from golden-cs culture-json (.NET ${'10'} with ICU).
// Do not edit by hand: run \`node packages/reportman-engine/test/generate-cultures.mjs\` from typescript/.
/* eslint-disable */
import type { CultureData } from './culture.js';

`;
const body = 'export const CULTURE_DATA: Readonly<Record<string, CultureData>> = ' + JSON.stringify(result, null, 2) + ';\n';
fs.writeFileSync(outFile, header + body);
console.log('wrote', outFile, Object.keys(result).length, 'cultures');
