// The date masks of the reports converted from Delphi (decision of 22-11-2026: Delphi's
// FormatDateTime for them, .NET's masks for the others), from Delphi itself
// (tools/golden-delphi-dates, built with its build.bat):
//
//   src/util/delphiformatsettings.generated.ts      the format settings Delphi takes from Windows
//   Reportman.Reporting/DelphiFormatSettingsData.cs (TFormatSettings.Create) for the cultures of
//                                                   the engine, and the era of their calendar
//   test/fixtures/delphi-dates.json                 FormatDateTime of masks (those compared with
//                                                   Delphi on 21-11-2026, the edges of each token
//                                                   and random ones) for some dates in each
//                                                   culture: what Delphi gives and what the C#
//                                                   engine gives (golden-cs delphi-dates)
//
// The tables are written first and golden-cs is built again with them.
//
//   node test/generate-delphi-date-fixtures.mjs        (from packages/reportman-engine)

import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../../..');
const delphi = path.join(root, 'typescript/tools/golden-delphi-dates/bin_x86/delphi-dates.exe');
const goldenCs = path.join(root, 'typescript/tools/golden-cs');
const goldenCsExe = path.join(goldenCs, 'bin/Release/net10.0/golden-cs.exe');
const work = fs.mkdtempSync(path.join(os.tmpdir(), 'rm-delphi-dates-'));

function run(exe, args, options = {}) {
  const r = spawnSync(exe, args, { encoding: 'utf8', ...options });
  if (r.status !== 0) throw new Error(path.basename(exe) + ' ' + args.join(' ') + ' failed: ' + r.stdout + r.stderr);
}

// ---------------------------------------------------------------------------------------------
// The format settings

// The cultures of the TypeScript engine (CultureInfo.get); '' is the invariant one
const CULTURES = ['', 'en-US', 'es-ES', 'ca-ES', 'pt-BR', 'fr-FR', 'de-DE', 'it-IT'];
const settingsFile = path.join(work, 'settings.json');
run(delphi, ['settings', settingsFile, ...CULTURES.map((c) => (c === '' ? '-' : c))]);
const settings = JSON.parse(fs.readFileSync(settingsFile, 'utf8'));

const HEADER = `Generated by packages/reportman-engine/test/generate-delphi-date-fixtures.mjs from Delphi
// (typescript/tools/golden-delphi-dates): the format settings of each culture as
// TFormatSettings.Create gives them on Windows ('' is TFormatSettings.Invariant), and the era of
// its calendar, for the date masks of the reports converted from Delphi.`;

const ts = [`// ${HEADER}`, '', "import type { DelphiFormatSettings } from './delphidateformat.js';", ''];
ts.push('export const DELPHI_FORMAT_SETTINGS: Readonly<Record<string, DelphiFormatSettings>> = {');
for (const c of CULTURES) ts.push(`  ${JSON.stringify(c)}: ${JSON.stringify(settings[c])},`);
ts.push('};', '');
fs.writeFileSync(path.join(root, 'typescript/packages/reportman-engine/src/util/delphiformatsettings.generated.ts'), ts.join('\n'));

const str = (s) => JSON.stringify(s);
const arr = (a) => 'new[] { ' + a.map(str).join(', ') + ' }';
const cs = [`// ${HEADER}`, 'using System;', 'using System.Collections.Generic;', '', 'namespace Reportman.Reporting', '{'];
cs.push('    internal static class DelphiFormatSettingsData', '    {');
cs.push('        internal static readonly Dictionary<string, DelphiFormatSettings> Cultures =');
cs.push('            new Dictionary<string, DelphiFormatSettings>(StringComparer.OrdinalIgnoreCase)', '        {');
for (const c of CULTURES) {
  const s = settings[c];
  cs.push(`            { ${str(c)}, new DelphiFormatSettings(${[s.shortDateFormat, s.longDateFormat, s.shortTimeFormat, s.longTimeFormat, s.timeAMString, s.timePMString, s.dateSeparator, s.timeSeparator].map(str).join(', ')},`);
  cs.push(`                ${arr(s.shortMonthNames)},`);
  cs.push(`                ${arr(s.longMonthNames)},`);
  cs.push(`                ${arr(s.shortDayNames)},`);
  cs.push(`                ${arr(s.longDayNames)}, ${str(s.eraName)}) },`);
}
cs.push('        };', '    }', '}', '');
fs.writeFileSync(path.join(root, 'Reportman.Reporting/DelphiFormatSettingsData.cs'), cs.join('\r\n'));

// golden-cs with the new tables
run('dotnet', ['build', '-c', 'Release', '-nologo', '-v', 'q'], { cwd: goldenCs });

// ---------------------------------------------------------------------------------------------
// The cases

// A seeded generator (mulberry32), so the fixtures can be written again the same
let seed = 0x0da7e5;
function random() {
  seed = (seed + 0x6d2b79f5) | 0;
  let t = seed;
  t = Math.imul(t ^ (t >>> 15), t | 1);
  t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
  return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
}

// The masks compared with Delphi on 21-11-2026 (the night of F2), then the edges of each token
const MASKS = [
  '', '/', ':', 'c', 'c tt', 'd', 'd/m/y', 'dd', 'dd.mm.yyyy', 'dd/mm/yy t', 'dd/mm/yyyy', 'dd/mm/yyyy hh:nn', 'ddd', 'dddd',
  'dddd, d "de" mmmm "de" yyyy', 'ddddd', 'ddddd tt', 'dddddd', 'e', 'ee', 'g', 'gg', 'h', 'h:n a/p', 'hh', 'hh"h"nn', 'hh:nn',
  'hh:nn am/pm', 'hh:nn ampm', 'hh:nn:ss', 'm', 'mm', 'mm/yyyy', 'mmm', 'mmm-yy', 'mmmm', 'n', 'nn', 's', 'ss', 't', 'tt', 'yy',
  'yyyy', 'yyyy-mm-dd"T"hh:nn:ss', 'z', 'zzz',
  // Minutes or month: m right after an h (letters in between break it, other characters do not)
  'hh:mm', 'h:m:s', 'mm:ss', 'hh:mm:ss', 'HH:MM', 'h m', 'h/m', 'hxm', 'hh "x" mm', 'dd/mmm/yyyy', 'mmmm yyyy', 'dddd d',
  // The 12 hour clock: am/pm, a/p and ampm before or after the hour, in quotes, in any case
  'h:mm am/pm', 'hh:nn AM/PM', 'hh:nn Am/Pm', 'hh:nn A/P', 'AM/PM hh', 'A/P', 'a/p h', 'AMPM', 'ampm h', 'hh "am/pm"', "hh 'am/pm'",
  'hh "x" am/pm', 'hh h am/pm', 'h am', 'hh:nn:ss.zzz am/pm',
  // A, AAA and AAAA
  'aaa', 'aaaa', 'AAAA, dd', 'a', 'xa', 'Aa',
  // The counts of each token
  'y', 'yyy', 'yyyyy', 'mmmmm', 'ddddddd', 'hhh', 'nnn', 'sss', 'zz', 'zzzz', 'eee', 'ggg', 'cc', 'ttt', 'Dd/Mm', 'dD',
  // Masks of .NET in a report from Delphi, quotes, other letters, other scripts
  'dd/MM/yyyy HH:mm', 'dd/MM/yyyy hh:mm tt', '"unterminated', "'single", "dd'x'", "d 'de' mmmm", 'q', 'yyyy年mm月dd日', 'd\u{1F600}m',
  'hh:nn:ss.zzz', 'dd-mm-yyyy hh:nn:ss', 'd/m/yyyy h:nn', 'ddd dd mmm', 'tt c', 'dddddd tt',
];
// 2026-11-23 (Monday) at midnight, 13:02:29.760 and 00:00:01; 1899-12-30 13:02:29.760 (a time);
// 2000-01-01 18:00 (Saturday); 1900-01-02 at noon; 2025-01-21 23:59:59.136; 2005-07-04 06:07:08
const VALUES = [46349.0, 46349.5434, 46349.0000116, 0.5434, 36526.75, 3.5, 45678.99999, 38537.254953703706];
const cases = [];
for (const culture of CULTURES) for (const mask of MASKS) for (const value of VALUES) cases.push({ culture, mask, value });
const ALPHABET = 'dmyhnsztacgeAMPDYHNS/:\'" -.x';
for (let k = 0; k < 120; k++) {
  const n = 1 + Math.floor(random() * 10);
  let mask = '';
  for (let i = 0; i < n; i++) mask += ALPHABET.charAt(Math.floor(random() * ALPHABET.length));
  const culture = CULTURES[Math.floor(random() * CULTURES.length)];
  for (const value of [46349.5434, 36526.75, 3.5]) cases.push({ culture, mask, value });
}

const casesFile = path.join(work, 'cases.json');
fs.writeFileSync(casesFile, JSON.stringify(cases));
const delphiOut = path.join(work, 'delphi.json');
const csOut = path.join(work, 'cs.json');
run(delphi, ['format', casesFile, delphiOut]);
run(goldenCsExe, ['delphi-dates', casesFile, csOut]);
const delphiResults = JSON.parse(fs.readFileSync(delphiOut, 'utf8'));
const csResults = JSON.parse(fs.readFileSync(csOut, 'utf8'));
fs.rmSync(work, { recursive: true });

const rows = cases.map((c, i) => JSON.stringify([c.culture, c.mask, c.value, delphiResults[i], csResults[i]]));
fs.writeFileSync(path.join(here, 'fixtures', 'delphi-dates.json'), '[\n' + rows.join(',\n') + '\n]\n');
const csWrong = cases.filter((_, i) => delphiResults[i] !== csResults[i]).length;
console.log(`${cases.length} cases; C# differs from Delphi in ${csWrong}`);
