// The tables of CHSTOCHT and CHTTOCHS, from what Windows gives the Delphi engine (LCMapString of the
// locale zh-CN, golden-cs lcmap): every UTF-16 code unit LCMAP_TRADITIONAL_CHINESE or
// LCMAP_SIMPLIFIED_CHINESE changes, one character for one. Writes the table of both engines,
// src/eval/chinesetables.ts and Reportman.Reporting/ChineseTables.cs, and fixtures/chinese.json
// with texts Windows mapped whole, which test/chinese.test.ts checks against the tables.
//
//   node test/generate-chinese-tables.mjs     (from packages/reportman-engine, Windows)

import { execFileSync } from 'node:child_process';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '../../../..');
const golden = path.join(root, 'typescript/tools/golden-cs/bin/Release/net10.0/golden-cs.exe');
const out = path.join(os.tmpdir(), 'rm-lcmap.json');
const TEXTS = [
  '简体中文测试', '繁體中文測試', '汉字 漢字 abc 123', '发 髮 發', '后 後', '干 乾 幹', '里 裡 裏', '这是一个报表的标题：销售汇总',
  '這是一個報表的標題：銷售彙總', '国际 國際 电脑 電腦 软件 軟體', '台湾 臺灣 台灣', '面 麵 云 雲', '', 'Report Manager',
];
execFileSync(golden, ['lcmap', out, ...TEXTS]);
const data = JSON.parse(fs.readFileSync(out, 'utf8'));

const pairs = (map) => {
  const keys = Object.keys(map).map(Number).sort((a, b) => a - b);
  for (const k of keys) if (map[k].length !== 1) throw new Error('not one for one: ' + k);
  return { from: keys.map((k) => String.fromCharCode(k)).join(''), to: keys.map((k) => map[k]).join('') };
};
const traditional = pairs(data.traditional);
const simplified = pairs(data.simplified);
const header = (comment) =>
  `${comment} Generated by packages/reportman-engine/test/generate-chinese-tables.mjs from LCMapString of Windows
${comment} (the locale zh-CN, as the Delphi engine calls it): the characters LCMAP_TRADITIONAL_CHINESE and
${comment} LCMAP_SIMPLIFIED_CHINESE change, each one into the character at its index.
`;
fs.writeFileSync(
  path.join(here, '..', 'src', 'eval', 'chinesetables.ts'),
  header('//') +
    `export const TO_TRADITIONAL_FROM = ${JSON.stringify(traditional.from)};
export const TO_TRADITIONAL_TO = ${JSON.stringify(traditional.to)};
export const TO_SIMPLIFIED_FROM = ${JSON.stringify(simplified.from)};
export const TO_SIMPLIFIED_TO = ${JSON.stringify(simplified.to)};
`,
);
fs.writeFileSync(
  path.join(root, 'Reportman.Reporting', 'ChineseTables.cs'),
  header('//') +
    `namespace Reportman.Reporting
{
    internal static class ChineseTables
    {
        public const string ToTraditionalFrom = ${JSON.stringify(traditional.from)};
        public const string ToTraditionalTo = ${JSON.stringify(traditional.to)};
        public const string ToSimplifiedFrom = ${JSON.stringify(simplified.from)};
        public const string ToSimplifiedTo = ${JSON.stringify(simplified.to)};
    }
}
`.replace(/\n/g, '\r\n'),
);
fs.writeFileSync(path.join(here, 'fixtures', 'chinese.json'), JSON.stringify(data.texts, null, 1) + '\n');
console.log(`traditional ${traditional.from.length}, simplified ${simplified.from.length}, ${data.texts.length} texts`);
