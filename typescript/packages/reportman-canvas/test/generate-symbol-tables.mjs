// The characters of the bytes of the Symbol and ZapfDingbats standard fonts (their built-in
// encodings) and their widths, for the preview, which draws them with a browser font where a PDF
// viewer would: src/symboltables.ts. The characters from the encodings of @pdf-lib/standard-fonts
// (MIT: each Unicode character with its code and glyph name), checked against the AFM files of Adobe
// (the code and the name of each glyph), and the widths from those AFM files. A code that more than
// one character stands for (Delta: U+0394 and U+2206) gets the lowest one, the letter.
//
//   node test/generate-symbol-tables.mjs <@pdf-lib/standard-fonts folder> <folder of Symbol.afm and ZapfDingbats.afm>
import { createRequire } from 'node:module';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const [pdfLib, afmDir] = process.argv.slice(2);
if (!pdfLib || !afmDir) {
  console.error('usage: node test/generate-symbol-tables.mjs <@pdf-lib/standard-fonts folder> <AFM folder>');
  process.exit(2);
}
const here = path.dirname(fileURLToPath(import.meta.url));
const require = createRequire(import.meta.url);
const { Encodings } = require(path.join(pdfLib, 'lib', 'Encoding.js'));

/** code -> glyph name and width of an AFM file (C code ; WX width ; N name ; ...). */
function afmGlyphs(file) {
  const glyphs = new Map();
  for (const line of fs.readFileSync(file, 'latin1').split(/\r?\n/)) {
    const m = /^C (\d+) ; WX (\d+) ; N ([^ ;]+) ;/.exec(line);
    if (m !== null) glyphs.set(Number(m[1]), { name: m[3], width: Number(m[2]) });
  }
  return glyphs;
}

function table(encoding, afmFile) {
  const byCode = new Map();
  for (const cp of encoding.supportedCodePoints) {
    const { code, name } = encoding.encodeUnicodeCodePoint(cp);
    const known = byCode.get(code);
    if (known === undefined || cp < known.cp) byCode.set(code, { cp, name });
  }
  const glyphs = afmGlyphs(afmFile);
  for (const [code, { name }] of glyphs) {
    const e = byCode.get(code);
    if (e === undefined) throw new Error(`${path.basename(afmFile)}: code ${code} (${name}) has no character`);
    if (e.name !== name) throw new Error(`${path.basename(afmFile)}: code ${code} is ${name} in the AFM and ${e.name} in the encoding`);
  }
  for (const code of byCode.keys()) if (!glyphs.has(code)) throw new Error(`${path.basename(afmFile)}: code ${code} is not in the AFM`);
  // As an array of strings: a character above U+FFFF (none today) still takes one entry
  const chars = [...Array(256).keys()].map((c) => (byCode.get(c) === undefined ? '' : String.fromCodePoint(byCode.get(c).cp)));
  const widths = [...Array(256).keys()].map((c) => glyphs.get(c)?.width ?? 0);
  return { chars, widths };
}

const symbol = table(Encodings.Symbol, path.join(afmDir, 'Symbol.afm'));
const dingbats = table(Encodings.ZapfDingbats, path.join(afmDir, 'ZapfDingbats.afm'));
const lines = (t) => {
  const out = [];
  for (let i = 0; i < 256; i += 16) out.push('  ' + t.slice(i, i + 16).map((c) => JSON.stringify(c)).join(', ') + ',');
  return out.join('\n');
};
const notice = fs
  .readFileSync(path.join(afmDir, 'Symbol.afm'), 'latin1')
  .split(/\r?\n/)
  .find((l) => l.startsWith('Comment Copyright'))
  .replace('Comment ', '');
fs.writeFileSync(
  path.join(here, '..', 'src', 'symboltables.ts'),
  `// Generated by test/generate-symbol-tables.mjs: the character each byte of the Symbol and
// ZapfDingbats standard fonts stands for (their built-in encodings), '' for a byte without a glyph,
// and its width in thousandths of the em, the one a PDF viewer advances by. From the AFM files of
// Adobe (${notice}),
// which may be used, copied and distributed for any purpose with their copyright notices.

/** Symbol: the byte as index. */
export const SYMBOL_CHARS: readonly string[] = [
${lines(symbol.chars)}
];

/** The widths of Symbol, the byte as index. */
export const SYMBOL_WIDTHS: readonly number[] = [
${lines(symbol.widths)}
];

/** ZapfDingbats: the byte as index. */
export const DINGBATS_CHARS: readonly string[] = [
${lines(dingbats.chars)}
];

/** The widths of ZapfDingbats, the byte as index. */
export const DINGBATS_WIDTHS: readonly number[] = [
${lines(dingbats.widths)}
];
`,
);
console.log(`Symbol ${symbol.chars.filter(Boolean).length} codes, ZapfDingbats ${dingbats.chars.filter(Boolean).length} codes`);
